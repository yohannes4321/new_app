// Firebase options generated by FlutterFire CLI
import 'firebase_options.dart';

@pragma('vm:entry-point')
Future<void> _firebaseMessagingBackgroundHandler(RemoteMessage message) async {
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  print("Handling a background message: ${message.messageId}");
}

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  try {
    // Ensure 'DefaultFirebaseOptions' includes Web/Android support
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );

    FirebaseMessaging.onBackgroundMessage(_firebaseMessagingBackgroundHandler);

    await GetStorage.init();

    // Inject Services
    final authService = Get.put(AuthService());
    await authService.hydrateSession();
    Get.put(NotificationService());

    // Inject Repositories
    Get.put(EventsRepository());
    Get.put(TestimoniesRepository());
    Get.put(HomeRepository());
    Get.put(BooksService());
    Get.put(BooksRepository());
    Get.put(SubscriptionRepository());
    Get.put(ProfileRepository());
    Get.put(OfflineMediaService());

    runApp(const MyApp());
  } catch (error) {
    runApp(InitErrorApp(error: error));
  }
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    // Keep the root widget testable and resilient when startup dependency
    // injection has not completed yet (for example during a cold launch).
    final auth = Get.isRegistered<AuthService>() ? Get.find<AuthService>() : null;
    return GetMaterialApp(
      debugShowCheckedModeBanner: false,
      title: "Church App",

      initialRoute: auth?.isLoggedIn.value == true ? Routes.HOME : Routes.SIGN_IN,

      getPages: AppPages.routes,

      theme: ThemeData(
        useMaterial3: true,
        colorSchemeSeed: const Color(0xFF4C734D), // Your Church Green
        brightness: Brightness.light, // Change to Brightness.dark for Dark Mode
      ),
    );
  }
}

